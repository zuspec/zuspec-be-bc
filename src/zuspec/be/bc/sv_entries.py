"""
sv_entries.py -- a SystemVerilog task per action entry of an image (F2.3b).

A testbench calls an exported action with typed arguments instead of
``+pssvm_args``::

    import pssvm_entries_pkg::*;
    bit ok;
    pss_top_X(ctxt, 8'd5, ok);      // export X(bit[8] mode);

Each task widens its arguments to 64 bits (sign-extending a signed one) in
parameter order and runs the entry with ``zsp_rt_bc_ctxt.call`` (pssvm_pkg.sv),
which fixes those fields of the action before it is solved. An action
without parameters gets a task with only ``ctxt`` and ``ok``.
"""
import re
from typing import List

from .model import ZbcModel

# SV keywords a PSS identifier may spell; such a name gets a trailing '_'.
_SV_KEYWORDS = frozenset("""
always and assign begin bit buf byte case cell class config const cover
default disable do edge else end endcase event final for force forever fork
function generate genvar if import initial inout input int integer interface
join large let logic longint medium module nand negedge new nor not null or
output package packed parameter posedge program property real reg release
repeat return sequence shortint signed small specify static string struct
super supply0 supply1 table task this time tri type typedef union unique
unsigned use var virtual void wait while wire with xor
""".split())

_RESERVED = ("ctxt", "ok", "pss_args", "pss_ret")


def _ident(name: str, taken=()) -> str:
    """*name* as an SV identifier: non-word characters as '_', and a
    trailing '_' while it is a keyword or in *taken*."""
    s = re.sub(r"\W", "_", name)
    while s in _SV_KEYWORDS or s in taken:
        s += "_"
    return s


def task_name(qname: str) -> str:
    """The task for the action *qname*: ``pss_top::X`` -> ``pss_top_X``."""
    return _ident(qname.replace("::", "_"))


def _arg(name: str, desc: dict, qname: str) -> str:
    w = int(desc.get("width") or 0)
    if not 0 < w <= 64:
        raise ValueError(f"export {qname}: parameter {name!r} has no SV "
                         f"type (kind {desc.get('kind')!r}, width {w})")
    signed = " signed" if desc.get("signed") else ""
    rng = f" [{w - 1}:0]" if w > 1 else ""
    return f"bit{signed}{rng}"


def emit(model: ZbcModel, package: str = "pssvm_entries_pkg") -> str:
    """The text of SV package *package*: a task per action entry of
    *model*, in entry order."""
    out: List[str] = [
        f"// {package} -- generated by `pssc sv-entries`; do not edit.",
        "// A task per action entry: task(ctxt, <parameters>, output ok).",
        f"package {package};",
        "  import zsp_rt_bc_pkg::*;",
        "  import pssvm_pkg::*;",
    ]
    names = set()
    for e in (getattr(model, "entries", None) or {}).values():
        if e.kind != "action" or not e.qname:
            continue
        tname = task_name(e.qname)
        if tname in names:
            raise ValueError(f"entry {e.qname}: task {tname} is already defined")
        names.add(tname)
        ports = ["zsp_rt_bc_ctxt ctxt"]
        pushes = []
        taken = set(_RESERVED)
        for pname, desc in e.params:
            p = _ident(pname, taken)
            taken.add(p)
            ports.append(f"input {_arg(pname, desc, e.qname)} {p}")
            v = f"longint'({p})" if desc.get("signed") else p
            pushes.append(f"    pss_args.push_back(64'({v}));")
        ports.append("output bit ok")
        out += [
            "",
            f"  // {e.qname}" + (f"({', '.join(n for n, _ in e.params)})"
                                 if e.params else ""),
            f"  task automatic {tname}({', '.join(ports)});",
            "    longint unsigned pss_args[$];",
            "    longint unsigned pss_ret;",
            *pushes,
            f'    ctxt.call("{e.qname}", "", pss_args, pss_ret, ok);',
            "  endtask",
        ]
    out += ["", f"endpackage : {package}", ""]
    return "\n".join(out)
